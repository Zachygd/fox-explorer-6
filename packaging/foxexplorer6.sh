#!/bin/sh
# Fox Explorer 6 launcher
FE6_HOME="${FE6_HOME:-@LIBDIR@}"
INI="$FE6_HOME/browser/foxexplorer6.ini"

# ---------------------------------------------------------------------------------------------
# Square windows: Firefox draws its own title bar, and GTK then adds a window frame around it
# from the GTK theme (rounded corners and a drop shadow with Breeze, a beige bevel with
# Chicago95). Fox Explorer has its own Windows 98 frame, so give this process a small GTK theme
# of its own: it loads your current GTK theme unchanged and only takes that outer frame away.
# Other apps are not affected. Set FE6_KEEP_GTK_FRAME=1 to skip this.
fe6_gtk_theme() {
  [ -n "$FE6_KEEP_GTK_FRAME" ] && return 0
  conf="${XDG_CONFIG_HOME:-$HOME/.config}"
  ini="$conf/gtk-3.0/settings.ini"
  name="${GTK_THEME%%:*}"; dark=""
  case "$GTK_THEME" in *:dark) dark=1;; esac
  if [ -z "$name" ] && command -v gsettings >/dev/null 2>&1; then
    name="$(gsettings get org.gnome.desktop.interface gtk-theme 2>/dev/null | tr -d "'")"
    [ "$(gsettings get org.gnome.desktop.interface color-scheme 2>/dev/null)" = "'prefer-dark'" ] && dark=1
  fi
  if [ -f "$ini" ]; then
    n="$(sed -n 's/^[[:space:]]*gtk-theme-name[[:space:]]*=[[:space:]]*//p' "$ini" | tail -1)"
    [ -n "$n" ] && [ -z "$GTK_THEME" ] && name="$n"
    grep -Eq '^[[:space:]]*gtk-application-prefer-dark-theme[[:space:]]*=[[:space:]]*(1|true)' "$ini" && dark=1
  fi
  [ -n "$name" ] || name=Adwaita
  case "$name" in *-dark|*-Dark) dark=1;; esac
  [ "$name" = FoxExplorer6 ] && return 0

  # find the theme's own stylesheet (gtk-dark.css for its dark variant)
  want=gtk.css; [ -n "$dark" ] && want=gtk-dark.css
  src=""
  for d in "${XDG_DATA_HOME:-$HOME/.local/share}/themes" "$HOME/.themes" \
           $(printf '%s' "${XDG_DATA_DIRS:-/usr/local/share:/usr/share}" | tr ':' ' ' | sed 's|\([^ ]*\)|\1/themes|g') \
           /usr/share/themes; do
    for f in "$d/$name/gtk-3.0/$want" "$d/$name/gtk-3.0/gtk.css"; do
      if [ -f "$f" ]; then src="file://$f"; break 2; fi
    done
  done
  if [ -z "$src" ]; then
    case "$name" in
      Adwaita|adwaita|Default|"") [ -n "$dark" ] && src="resource:///org/gtk/libgtk/theme/Adwaita/gtk-contained-dark.css" \
                                              || src="resource:///org/gtk/libgtk/theme/Adwaita/gtk-contained.css";;
      HighContrast*) src="resource:///org/gtk/libgtk/theme/HighContrast/gtk-contained.css";;
      *) return 0;;   # unknown theme: leave GTK alone
    esac
  fi

  base="${XDG_CACHE_HOME:-$HOME/.cache}/foxexplorer6/gtk"
  dir="$base/themes/FoxExplorer6/gtk-3.0"
  mkdir -p "$dir" 2>/dev/null || return 0
  cat > "$dir/gtk.css.new" <<CSS || return 0
/* Generated by the Fox Explorer 6 launcher: your GTK theme ($name), minus the outer window
   frame, so Fox Explorer's own Windows 98 frame is the edge of the window. */
@import url("$src");

decoration, window.csd decoration, window.csd.maximized decoration, window.solid-csd decoration,
window.csd:backdrop decoration, window.csd.popup decoration, window.csd.dialog decoration {
  border: none;
  border-image: none;
  outline: none;
  padding: 0;
  border-radius: 0;
  margin: 0;
  /* a transparent band keeps the edges grabbable for resizing, without drawing anything */
  box-shadow: 0 0 0 4px transparent;
}
window.csd.maximized decoration, window.csd.tiled decoration, window.csd.fullscreen decoration {
  box-shadow: none;
}
window, window.csd, headerbar, .titlebar, window.csd > .titlebar:not(headerbar) {
  border-radius: 0;
}
CSS
  mv -f "$dir/gtk.css.new" "$dir/gtk.css"
  cp -f "$dir/gtk.css" "$dir/gtk-dark.css"
  export XDG_DATA_DIRS="$base:${XDG_DATA_DIRS:-/usr/local/share:/usr/share}"
  export GTK_THEME=FoxExplorer6
}
fe6_gtk_theme

if [ -f "$INI" ]; then
  exec "$FE6_HOME/@BINARY@" -app "$INI" --name foxexplorer6 --class foxexplorer6 "$@"
else
  exec "$FE6_HOME/@BINARY@" --name foxexplorer6 --class foxexplorer6 "$@"
fi
