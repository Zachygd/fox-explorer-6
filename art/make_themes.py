#!/usr/bin/env python3
"""Generate Fox Explorer's Cathode colour themes from the Cathode KDE theme.

Usage:  art/make_themes.py /path/to/Cathode-KDE-Theme

Reads build/schemes.py from the Cathode KDE theme (https://github.com/Zachygd/Cathode-KDE-Theme),
the single table that defines every Cathode scheme, and writes:

  theme/fe6/fe6-themes.css   one light and one dark palette per scheme, keyed on
                             <html fe6-theme="slug">, using Cathode's own grays so Fox Explorer
                             matches the Cathode taskbar and windows exactly
  fe6-boot.sys.mjs           the THEMES table (between the GENERATED THEMES markers), used for
                             View > Theme and the Internet Options drop-down

"Windows Standard" (no fe6-theme attribute) is the classic Windows 98 palette in fe6-palette.css.
"""
import importlib.util, json, os, re, sys

# Cathode's shared base colours (gen_colors.py / svgkit.py in the Cathode theme)
BASE = {
    False: dict(face="#c0c0c0", light="#dfdfdf", hi="#ffffff", shadow="#808080", dark="#000000",
                text="#000000", graytext="#808080", window="#f4f3ef", wintext="#000000",
                capi1="#808080", capi2="#c0c0c0", capitext="#c0c0c0", tip="#ffffe1", tiptext="#000000",
                cold="grayscale(1)", disabled="grayscale(1) opacity(.45)"),
    True: dict(face="#3a3a3a", light="#4a4a4a", hi="#686868", shadow="#242424", dark="#000000",
               text="#e8e8e8", graytext="#969696", window="#2a2a2a", wintext="#e8e8e8",
               capi1="#2c2c2c", capi2="#4e4e4e", capitext="#969696", tip="#30302a", tiptext="#e8e8e8",
               # plain grayscale keeps the SE98 icons' detail on dark gray; brightening washes them out
               cold="grayscale(1) contrast(1.15)", disabled="grayscale(1) opacity(.4)"),
}


def grad(stops, direction="to right"):
    return f"linear-gradient({direction}, " + ", ".join(f"{c} {round(p * 100)}%" for p, c in stops) + ")"


def block(s, dark):
    b = BASE[dark]
    link = s["link_dark"] if dark else s["link_light"]
    v = {
        "face": b["face"], "light": b["light"], "hi": b["hi"], "shadow": b["shadow"], "dark": b["dark"],
        "text": b["text"], "graytext": b["graytext"], "window": b["window"], "wintext": b["wintext"],
        "sel": s["sel"], "seltext": "#ffffff",
        "cap1": s["deep"], "cap2": s["tip"], "capi1": b["capi1"], "capi2": b["capi2"],
        "captext": "#ffffff", "capitext": b["capitext"], "tip": b["tip"], "tiptext": b["tiptext"],
        "link": link, "progress": s["sel"],
        "cold-filter": b["cold"], "disabled-filter": b["disabled"],
        # accents (only drawn when a Cathode theme is active, see fe6.css "Cathode accents")
        "accent": s["sel"], "accent-text": link, "accent-deep": s["deep"], "accent-tip": s["tip"],
        "cap-grad": grad(s["title"]), "accent-grad-v": grad(s["title"], "to bottom"),
    }
    return "\n".join(f"  --fe-{k}: {val};" for k, val in v.items())


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    spec = importlib.util.spec_from_file_location("schemes", os.path.join(sys.argv[1], "build", "schemes.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    here = os.path.dirname(os.path.abspath(__file__))
    fe6 = os.path.join(here, "..", "theme", "fe6")

    css = ["/* Generated by art/make_themes.py from the Cathode KDE theme's build/schemes.py. Don't edit. */"]
    # The base "Cathode" colour scheme (no fe6-theme attribute): the standard blue Cathode98
    # scheme, without the colour accents. "Cathode Color" (fe6-theme="cathode") adds them.
    base = mod.BY_SLUG["cathode"] if hasattr(mod, "BY_SLUG") else mod.ALL[0]
    sel = ":root:not([fe6-theme])"
    css.append(f"{sel} {{\n{block(base, False)}\n}}")
    css.append(f'{sel}[fe6-scheme="dark"] {{\n{block(base, True)}\n}}')
    css.append(f"@media (prefers-color-scheme: dark) {{\n{sel}:not([fe6-scheme]) {{\n{block(base, True)}\n}}\n}}")
    for s in mod.ALL:
        sel = f':root[fe6-theme="{s["slug"]}"]'
        css.append(f"{sel} {{\n{block(s, False)}\n}}")
        css.append(f'{sel}[fe6-scheme="dark"] {{\n{block(s, True)}\n}}')
        css.append(f"@media (prefers-color-scheme: dark) {{\n{sel}:not([fe6-scheme]) {{\n{block(s, True)}\n}}\n}}")
    with open(os.path.join(fe6, "fe6-themes.css"), "w") as f:
        f.write("\n".join(css) + "\n")

    table = [{"id": s["slug"], "name": s["name"], "grad": grad(s["title"]), "sel": s["sel"],
              "deskLight": s["desk_light"], "deskDark": s["desk_dark"],
              "linkLight": s["link_light"], "linkDark": s["link_dark"]} for s in mod.ALL]
    boot = os.path.join(fe6, "fe6-boot.sys.mjs")
    src = open(boot).read()
    js = ("// GENERATED THEMES (art/make_themes.py) - don't edit by hand\n"
          "const THEMES = " + json.dumps(table, indent=1) + ";\n// END GENERATED THEMES")
    src, n = re.subn(r"// GENERATED THEMES.*?// END GENERATED THEMES", lambda m: js, src, flags=re.S)
    if n != 1:
        sys.exit("fe6-boot.sys.mjs has no GENERATED THEMES markers")
    open(boot, "w").write(src)
    print(f"wrote {len(mod.ALL)} Cathode themes (light + dark)")


if __name__ == "__main__":
    main()
