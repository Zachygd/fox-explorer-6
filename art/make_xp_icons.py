#!/usr/bin/env python3
"""Make Fox Explorer's Windows XP style icons from the Windows XP High Resolution Icon Pack.

The pack is by marchmountain (https://github.com/marchmountain/-Windows-XP-High-Resolution-Icon-Pack,
also on DeviantArt), released under CC0 1.0. Its icons are 1024x1024 PNGs; this scales the ones Fox
Explorer uses down to 24x24 (toolbars) and 16x16 (menus, sidebar, Library, status bar), draws the
Downloads button animation from the pack's globe, page and folder, and writes xp/xp-icons.css,
which applies them only in the Windows XP style (<html fe6-xp>).

Usage:  art/make_xp_icons.py "/path/to/Windows XP High Resolution Icon Pack"
The result is committed, so builds don't need the pack. Icons with Microsoft or MSN logos (the
Internet Explorer "e", the Windows flag, the MSN butterfly) are deliberately not used.
"""
import os, re, shutil, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
FE6 = os.path.join(HERE, "..", "theme", "fe6")
OUT = os.path.join(FE6, "xp")

# Fox Explorer icon name -> icon in the pack's "Windows XP Icons" folder
ICONS = {
    "back": "Back", "forward": "Forward", "stop": "IE Stop", "refresh": "IE Refresh",
    "home": "IE Home", "search": "Search", "favorites": "Favorites", "history": "IE History",
    "mail": "Email", "print": "Printer", "downloads": "Move to folder", "extensions": "WMP Plugin",
    "sidebar": "Folder View - Common Tasks", "go": "Go", "account": "User Accounts",
    "newtab": "Application Window", "newwindow": "Folders open in new window", "open": "Open",
    "save": "Save", "cut": "Cut", "copy": "Copy", "paste": "Paste", "find": "Document Search",
    "zoom-in": "IE Enlarge Image", "zoom-out": "IE Shrink Image", "fullscreen": "Full Screen",
    "settings": "Internet Options", "forget": "Recycle Bin (full)", "private": "Privacy",
    "fxview": "Recent Documents", "developer": "Command Prompt", "screenshot": "Take Picture",
    "import": "File and Settings Transfer Wizard", "library": "Explorer", "key": "Key",
    "share": "Sharing Hand", "synced": "Sync", "sendtab": "OE Send", "encoding": "IE Encoding",
    "tabgroups": "Tile View", "splitview": "Detail View", "pip": "Generic Video",
    "folder": "Folder Closed", "folder-favorites": "Favorites", "tag": "Attributes",
    "day": "Date and Time", "lock": "Padlock", "globe": "Internet Shortcut", "computer": "My Computer",
    "chat": "Windows Messenger", "reader": "Generic Text Document", "monitor": "Task Manager",
    "customize": "Appearance",
}
BIG, SMALL = 24, 16


def load(pack, name):
    p = os.path.join(pack, "Windows XP Icons", name + ".png")
    if not os.path.exists(p):
        sys.exit(f"the icon pack has no '{name}.png'")
    return Image.open(p).convert("RGBA")


def shrink(img, size):
    # two-step downscale keeps the 1-2px outlines crisp at toolbar sizes
    img = img.resize((size * 4, size * 4), Image.LANCZOS)
    return img.resize((size, size), Image.LANCZOS)


def download_animation(pack):
    """9 frames, like the 98 one: a page flies out of the globe, along the top and into the folder."""
    s = BIG
    globe = shrink(load(pack, "Internet Shortcut"), 14)
    folder = shrink(load(pack, "Folder Closed"), 14)
    page = shrink(load(pack, "Generic Document"), 8)
    path = [(6, 1), (9, 0), (12, 0), (15, 2), (15, 5), (15, 8), (14, 11), None, None]
    strip = Image.new("RGBA", (s * len(path), s), (0, 0, 0, 0))
    for i, pos in enumerate(path):
        f = Image.new("RGBA", (s, s), (0, 0, 0, 0))
        f.alpha_composite(globe, (0, 0))
        f.alpha_composite(folder, (s - 14, s - 14))
        if pos:
            f.alpha_composite(page, pos)
        strip.alpha_composite(f, (i * s, 0))
    strip.save(os.path.join(OUT, "downloading.png"))


def css_from_se98():
    """Reuse se98.css's selector list (every Firefox button Fox Explorer themes), scoped to XP."""
    src = open(os.path.join(FE6, "se98", "se98.css")).read().splitlines()
    out = ["/* Generated by art/make_xp_icons.py: Windows XP High Resolution Icon Pack by marchmountain "
           "(CC0 1.0), see xp/README.md. Only in the Windows XP style. */"]
    for line in src:
        m = re.match(r'^(.*?)\s*\{\s*list-style-image: url\("([a-z0-9-]+?)(-16)?\.png"\)(.*)$', line)
        if not m:
            continue
        sels, name, small, rest = m.groups()
        if name not in ICONS:
            continue                                   # no XP icon: keep the SE98 one
        if sels.startswith(":root"):
            sels = ", ".join(":root[fe6-xp]" + p.strip()[len(":root"):] for p in sels.split(", "))
        elif "::" in sels:                             # tree images: pseudo-elements can't go in :is()
            sels = ", ".join(":root[fe6-xp] " + p.strip() for p in sels.split(", "))
        else:
            sels = f":root[fe6-xp] :is({sels})"
        out.append(f'{sels} {{ list-style-image: url("{name}{small or ""}.png"){rest}')
    out += [
        # XP's toolbar icons are 24x24 ("large icons")
        ':root[fe6-xp] #nav-bar .toolbarbutton-1 > :is(.toolbarbutton-icon, .toolbarbutton-badge-stack) { width: 30px !important; height: 30px !important; padding: 3px !important; }',
        ':root[fe6-xp] #nav-bar .toolbarbutton-1 > .toolbarbutton-badge-stack > .toolbarbutton-icon { width: 24px !important; height: 24px !important; }',
        ':root[fe6-xp] #downloads-indicator-icon { list-style-image: url("downloads.png") !important; width: 24px !important; height: 24px !important; }',
        ':root[fe6-xp] #nav-bar #downloads-button > .toolbarbutton-badge-stack { grid-template-columns: 24px !important; grid-template-rows: 24px !important; }',
        ':root[fe6-xp] #nav-bar #downloads-button[progress] > .toolbarbutton-badge-stack { grid-template-rows: 22px 5px !important; }',
        ':root[fe6-xp] #downloads-button > .toolbarbutton-badge-stack > #downloads-indicator-anchor { width: 24px !important; height: 24px !important; }',
        ':root[fe6-xp] #nav-bar #downloads-button[progress] > .toolbarbutton-badge-stack > #downloads-indicator-anchor { height: 22px !important; }',
        ':root[fe6-xp] #downloads-button[progress] > .toolbarbutton-badge-stack > #downloads-indicator-anchor {'
        ' background-image: url("downloading.png") !important; background-size: 216px 24px !important; background-position-y: -1px;'
        ' animation-name: fe6-xp-downloading !important; }',
        '@keyframes fe6-xp-downloading { from { background-position-x: 0; } to { background-position-x: -216px; } }',
        ':root[fe6-xp] #nav-bar #downloads-button[progress] > .toolbarbutton-badge-stack > #downloads-indicator-progress-outer { width: 24px !important; }',
        ':root[fe6-xp] #fe6-go-button > .toolbarbutton-icon { width: 18px !important; height: 18px !important; }',
    ]
    with open(os.path.join(OUT, "xp-icons.css"), "w") as f:
        f.write("\n".join(out) + "\n")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    pack = sys.argv[1]
    shutil.rmtree(OUT, ignore_errors=True)
    os.makedirs(OUT)
    for ours, theirs in ICONS.items():
        img = load(pack, theirs)
        shrink(img, BIG).save(os.path.join(OUT, ours + ".png"))
        shrink(img, SMALL).save(os.path.join(OUT, ours + "-16.png"))
    download_animation(pack)
    css_from_se98()
    lic = os.path.join(HERE, "xp-icons-LICENSE")
    shutil.copyfile(lic, os.path.join(OUT, "LICENSE"))
    with open(os.path.join(OUT, "README.md"), "w") as f:
        f.write("# Windows XP style icons\n\n"
                "From the **Windows XP High Resolution Icon Pack** by marchmountain "
                "(https://github.com/marchmountain/-Windows-XP-High-Resolution-Icon-Pack), released "
                "under **CC0 1.0** (see LICENSE). They are recreations of Windows XP's icons; Windows "
                "and Windows XP are trademarks of Microsoft. Scaled down to 24x24 and 16x16 by "
                "`art/make_xp_icons.py`, which lists the icon each one comes from; `downloading.png` "
                "is drawn from the pack's globe, document and folder icons.\n")
    print("wrote", len(ICONS) * 2, "icons, downloading.png and xp-icons.css to", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
